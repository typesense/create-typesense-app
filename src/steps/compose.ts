import { createHash } from 'node:crypto'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { ADMIN_KEY_VAR, TYPESENSE_IMAGE } from '../constants.js'

export interface ComposeOptions {
  projectName: string
  /** The project directory. Its absolute path makes the compose name unique. */
  targetDir: string
  port: number
  /** The template's env file, relative to the project dir. Supplies the API key. */
  envFile: string
}

export const COMPOSE_FILE = 'docker-compose.yml'

/**
 * Project name plus a short hash of the absolute path, so two projects with the
 * same directory name in different parents get their own container and volume.
 */
export function composeProjectName(projectName: string, targetDir: string): string {
  const hash = createHash('sha256').update(path.resolve(targetDir)).digest('hex').slice(0, 6)
  // Compose names allow only lowercase letters, digits, dashes and underscores.
  return `${projectName.toLowerCase().replace(/[^a-z0-9_-]/g, '-')}-${hash}`
}

/**
 * The compose file is generated rather than shelling out to `docker run`, so
 * teardown is obvious and the user can read exactly what was started.
 *
 * No `${...}` substitution anywhere: the key arrives through `env_file`, which
 * the *container* reads. Compose only interpolates from `.env`, so a substituting
 * file broke `docker compose down` for any template whose env file is named
 * something else. This way every bare compose command works.
 */
export function composeFileContents({
  projectName,
  targetDir,
  port,
  envFile,
}: ComposeOptions): string {
  const name = composeProjectName(projectName, targetDir)
  return `# Generated by create-typesense-app. Safe to commit, and safe to edit.
#
# --enable-cors is the reason this file exists. Without it the browser cannot
# talk to Typesense directly and every search fails at the CORS preflight.
name: ${name}
services:
  typesense:
    image: ${TYPESENSE_IMAGE}
    container_name: ${name}-typesense
    restart: unless-stopped
    ports:
      - "${port}:8108"
    volumes:
      - typesense-data:/data
    # ${ADMIN_KEY_VAR} lives here, not in this file, so the key is never
    # committed. Typesense reads that variable itself, which is why no
    # substitution is needed and plain \`docker compose up\` works.
    env_file:
      - ${envFile}
    command:
      - "--data-dir=/data"
      - "--enable-cors"

# A named volume, not a bind mount, so \`docker compose down --volumes\`
# genuinely leaves nothing behind.
volumes:
  typesense-data:
`
}

/** Idempotent: same inputs rewrite byte-identical content. Returns the path written. */
export async function writeComposeFile(dir: string, options: ComposeOptions): Promise<string> {
  await mkdir(dir, { recursive: true })
  const filePath = path.join(dir, COMPOSE_FILE)
  await writeFile(filePath, composeFileContents(options), 'utf8')
  return filePath
}
